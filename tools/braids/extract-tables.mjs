// Pulls the lookup tables out of Mutable Instruments' Braids sources (MIT, (c) Emilie Gillet) and writes them as
// worklet source text: `node tools/braids/extract-tables.mjs <eurorack checkout>`. Every table of braids/resources.cc
// is kept as the typed array of its C type, named BR_ and its own name (lut_svf_cutoff is BR_LUT_SVF_CUTOFF); the
// tables of pointers that only group them are left out.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2];
if (!root) throw new Error('usage: node tools/braids/extract-tables.mjs <path to a checkout of github.com/pichenettes/eurorack>');

const TYPES = { int8_t: 'Int8Array', uint8_t: 'Uint8Array', int16_t: 'Int16Array', uint16_t: 'Uint16Array', int32_t: 'Int32Array', uint32_t: 'Uint32Array' };
const src = readFileSync(join(root, 'braids/resources.cc'), 'utf8').replace(/\/\/.*$/gm, '');
const decl = /const\s+(u?int(?:8|16|32)_t)\s+(\w+)\[\]\s*=\s*\{([^}]*)\}/g;

let out = `// Generated by tools/braids/extract-tables.mjs from Mutable Instruments' Braids sources.
// Copyright 2012 Emilie Gillet (emilie.o.gillet@gmail.com), MIT licence (see src/audio/braids/LICENSE).
// Do not edit: run the script again.

/** The tables as worklet source text: each a typed array named BR_ and the original's name, in capitals. */
export const BRAIDS_TABLES_SOURCE = \`\n`;
let n = 0;
for (const [, type, name, body] of src.matchAll(decl)) {
  const values = body.split(',').map((s) => s.trim()).filter(Boolean);
  out += `const BR_${name.toUpperCase()} = ${TYPES[type]}.from([${values.join(',')}]);\n`;
  n++;
}
out += '`;\n';
writeFileSync(new URL('../../src/audio/braids/braidsTables.ts', import.meta.url), out);
console.log(`wrote ${n} tables, ${(out.length / 1024).toFixed(0)} KB`);
