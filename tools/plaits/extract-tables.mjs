// Pulls lookup tables out of Mutable Instruments' C++ sources (Plaits, Braids, stmlib; MIT, (c) Emilie Gillet) and
// writes them as worklet source text: `node tools/plaits/extract-tables.mjs <eurorack checkout>`.
// Float tables keep their C literals, so Float32Array holds exactly the floats the original was built with.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2];
if (!root) throw new Error('usage: node tools/plaits/extract-tables.mjs <path to a checkout of github.com/pichenettes/eurorack, with stmlib>');

/** [source file, table name, JS name, typed array] */
const TABLES = [
  ['stmlib/dsp/units.cc', 'lut_pitch_ratio_high', 'PL_PITCH_RATIO_HIGH', 'Float32Array'],
  ['stmlib/dsp/units.cc', 'lut_pitch_ratio_low', 'PL_PITCH_RATIO_LOW', 'Float32Array'],
  ['plaits/resources.cc', 'lut_sine', 'PL_SINE', 'Float32Array'],
  ['plaits/resources.cc', 'lut_fm_frequency_quantizer', 'PL_FM_FREQUENCY_QUANTIZER', 'Float32Array'],
  ['plaits/resources.cc', 'lut_fold', 'PL_FOLD', 'Float32Array'],
  ['plaits/resources.cc', 'lut_fold_2', 'PL_FOLD_2', 'Float32Array'],
  ['plaits/resources.cc', 'lut_stiffness', 'PL_STIFFNESS', 'Float32Array'],
  ['plaits/resources.cc', 'lut_svf_shift', 'PL_SVF_SHIFT', 'Float32Array'],
  ['plaits/resources.cc', 'lut_4x_downsampler_fir', 'PL_4X_DOWNSAMPLER_FIR', 'Float32Array'],
  ['plaits/resources.cc', 'lut_ws_inverse_tan', 'PL_WS_INVERSE_TAN', 'Int16Array'],
  ['plaits/resources.cc', 'lut_ws_inverse_sin', 'PL_WS_INVERSE_SIN', 'Int16Array'],
  ['plaits/resources.cc', 'lut_ws_linear', 'PL_WS_LINEAR', 'Int16Array'],
  ['plaits/resources.cc', 'lut_ws_bump', 'PL_WS_BUMP', 'Int16Array'],
  ['plaits/resources.cc', 'lut_ws_double_bump', 'PL_WS_DOUBLE_BUMP', 'Int16Array'],
  ['plaits/resources.cc', 'lut_lpc_excitation_pulse', 'PL_LPC_EXCITATION_PULSE', 'Int8Array'],
  ['plaits/resources.cc', 'wav_integrated_waves', 'PL_INTEGRATED_WAVES', 'Int16Array'],
];

function table(file, name) {
  const src = readFileSync(join(root, file), 'utf8');
  const at = src.search(new RegExp(`\\b${name}\\[\\]\\s*=\\s*\\{`));
  if (at < 0) throw new Error(`${name} not found in ${file}`);
  const body = src.slice(src.indexOf('{', at) + 1, src.indexOf('}', at));
  return body.split(',').map((s) => s.trim()).filter(Boolean).map((s) => s.replace(/f$/, ''));
}

let out = `// Generated by tools/plaits/extract-tables.mjs from Mutable Instruments' Plaits and stmlib sources.
// Copyright 2016-2021 Emilie Gillet (emilie.o.gillet@gmail.com), MIT licence (see src/audio/plaits/LICENSE).
// Do not edit: run the script again.

/** The tables as worklet source text: each a typed array named as in PL_* below. */
export const PLAITS_TABLES_SOURCE = \`\n`;
for (const [file, name, js, type] of TABLES) {
  const values = table(file, name);
  out += `const ${js} = ${type}.from([${values.join(',')}]);\n`;
}
out += '`;\n';
writeFileSync(new URL('../../src/audio/plaits/plaitsTables.ts', import.meta.url), out);
console.log(`wrote ${TABLES.length} tables, ${(out.length / 1024).toFixed(0)} KB`);
